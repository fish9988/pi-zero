/**
 * Pi Zero 内置 `ask_question` Pi 扩展生成器（纯 ESM，零外部依赖）。
 *
 * - 落盘到系统临时目录 `pi-zero-extensions/pi-zero-ask-question.mjs`（绝不写入 `~/.pi/agent`）；
 * - 仅使用 Pi 原生 `pi.registerTool(...)` 与标准 `ctx.ui.select(...)` RPC 交互协议；
 * - 让任意普通对话（无需安装或进入 plan 插件）下，模型均可按需呼出结构化 QA 面板。
 */
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

export const PI_BUILTIN_ASK_QUESTION_TOOL_NAME = "ask_question";

export const PI_ASK_QUESTION_EXTENSION_SOURCE = `// Auto-generated by Pi Zero — built-in ask_question extension (zero external deps)
export default function piZeroAskQuestionExtension(pi) {
  pi.registerTool({
    name: "ask_question",
    label: "Ask Question",
    description:
      "Ask the user 1 to 4 concise structured clarifying questions with multiple-choice options when requirements, scope, or preferences are genuinely ambiguous. Each question displays an interactive QA card with a built-in custom answer input row.",
    promptSnippet: "Ask the user structured multiple-choice clarifying questions via the interactive QA panel",
    promptGuidelines: [
      "Only call ask_question when a decision genuinely needs the user's preference or clarification; do not ask trivial yes/no questions.",
      "Provide 2 to 5 concise options per question without manual numbering prefixes (the UI numbers options automatically) and without a redundant 'Other' option (the UI provides a custom answer input automatically).",
      "Use a short 2-12 char 'header' tag when helpful to categorize the question.",
    ],
    defaultActive: true,
    parameters: {
      type: "object",
      additionalProperties: false,
      required: ["questions"],
      properties: {
        questions: {
          type: "array",
          minItems: 1,
          maxItems: 4,
          description: "List of structured clarifying questions to ask the user.",
          items: {
            type: "object",
            additionalProperties: false,
            required: ["question", "options"],
            properties: {
              header: {
                type: "string",
                description: "Short category tag shown as a badge (2-12 chars).",
              },
              question: {
                type: "string",
                description: "Clear, concise question text for the user.",
              },
              options: {
                type: "array",
                minItems: 2,
                maxItems: 6,
                items: {
                  type: "object",
                  additionalProperties: false,
                  required: ["label"],
                  properties: {
                    label: {
                      type: "string",
                      description: "Concise option label without numbering prefixes.",
                    },
                    description: {
                      type: "string",
                      description: "Optional brief explanation of this option.",
                    },
                  },
                },
              },
            },
          },
        },
      },
    },
    async execute(_toolCallId, params, signal, _onUpdate, ctx) {
      const list = Array.isArray(params?.questions) ? params.questions : [];
      if (list.length === 0) {
        return {
          content: [{ type: "text", text: "No questions were provided." }],
          details: { answers: {}, cancelled: false },
        };
      }
      if (!ctx?.ui?.select) {
        return {
          content: [
            {
              type: "text",
              text: "Interactive UI is unavailable in this environment. Ask the user directly in plain text instead.",
            },
          ],
          details: { answers: {}, unavailable: true },
        };
      }

      const answers = {};
      const lines = [];
      let cancelled = false;

      for (const item of list) {
        if (signal?.aborted) {
          cancelled = true;
          break;
        }
        const questionText = typeof item?.question === "string" ? item.question.trim() : "";
        if (!questionText) continue;
        const headerText = typeof item?.header === "string" ? item.header.trim() : "";
        const rawOptions = Array.isArray(item?.options) ? item.options : [];
        const optionLabels = rawOptions
          .map((opt) => {
            if (typeof opt === "string") return opt.trim();
            const label = typeof opt?.label === "string" ? opt.label.trim() : "";
            const desc = typeof opt?.description === "string" ? opt.description.trim() : "";
            if (!label) return "";
            return desc ? label + " — " + desc : label;
          })
          .filter((label) => label.length > 0);

        const promptTitle =
          headerText && headerText !== questionText
            ? "[" + headerText + "] " + questionText
            : questionText;

        const selected = await ctx.ui.select(
          promptTitle,
          optionLabels.length > 0 ? optionLabels : ["Confirm", "Cancel"],
        );

        if (selected === undefined || selected === null) {
          cancelled = true;
          lines.push("- " + questionText + ": (user dismissed)");
          break;
        }
        const answerText = String(selected).trim();
        answers[questionText] = answerText;
        lines.push("- " + questionText + ": " + answerText);
      }

      const summary = cancelled
        ? "User dismissed or cancelled the QA prompt." +
          (lines.length > 0 ? "\\n" + lines.join("\\n") : "")
        : "User answers:\\n" + lines.join("\\n");

      return {
        content: [{ type: "text", text: summary }],
        details: { answers, cancelled },
      };
    },
  });
}
`;

const EXTENSION_DIGEST = createHash("sha256")
  .update(PI_ASK_QUESTION_EXTENSION_SOURCE)
  .digest("hex")
  .slice(0, 12);

/** 将内置 `ask_question` 扩展落盘到系统临时目录（内容一致时复用，不触碰 `~/.pi/agent`）。 */
export async function ensureBuiltinAskQuestionExtensionFile(
  baseDir?: string | undefined,
): Promise<string> {
  const dir = baseDir ?? join(tmpdir(), "pi-zero-extensions");
  const target = join(dir, `pi-zero-ask-question-${EXTENSION_DIGEST}.mjs`);
  try {
    const existing = await readFile(target, "utf8");
    if (existing === PI_ASK_QUESTION_EXTENSION_SOURCE) return target;
  } catch {
    // 尚未创建，继续写入
  }
  await mkdir(dir, { recursive: true });
  await writeFile(target, PI_ASK_QUESTION_EXTENSION_SOURCE, "utf8");
  return target;
}
